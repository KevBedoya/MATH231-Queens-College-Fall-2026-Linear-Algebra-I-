def city():
    """Home locations of 320 customers of a food-truck company, in km.

    The customers live in four neighbourhoods of different sizes.  Returns X,
    an array with one location [x, y] per row.
    """
    rng = np.random.default_rng(231)
    #                 centre       spread  how many
    neighbourhoods = [((2.0, 2.0), 0.70, 120),    # downtown
                      ((6.0, 2.0), 0.80,  70),    # university
                      ((2.5, 6.5), 0.80,  70),    # harbour
                      ((7.0, 7.0), 1.10,  60)]    # suburbs
    points = []
    for (cx, cy), spread, n in neighbourhoods:
        points.append(np.column_stack([rng.normal(cx, spread, n),
                                       rng.normal(cy, spread, n)]))
    X = np.vstack(points)
    return X[rng.permutation(len(X))]


