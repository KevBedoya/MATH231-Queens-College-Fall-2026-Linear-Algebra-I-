def random_start(X, k, rng):
    """k distinct points of X chosen at random, to use as initial centres.

    This is the usual initialisation (computational unit Sec. 12.3, line 1).
    """
    rows = rng.choice(len(X), size=k, replace=False)
    return X[rows].copy()


