def songs():
    """A music app's songs, each described by two numbers:

        [duration in seconds, energy on a scale from 0 to 1]

    and labelled with its genre: "lofi", "pop" or "metal".

    Returns X_train, y_train (150 songs, 50 per genre) and X_test, y_test
    (90 songs, 30 per genre).
    """
    rng = np.random.default_rng(231)
    #            mean duration, sd duration, mean energy, sd energy
    genres = {"lofi":  (200, 40, 0.25, 0.10),
              "pop":   (210, 40, 0.60, 0.10),
              "metal": (240, 50, 0.85, 0.07)}
    X_train, y_train, X_test, y_test = [], [], [], []
    for label, (md, sd, me, se) in genres.items():
        for n, X_part, y_part in ((50, X_train, y_train), (30, X_test, y_test)):
            duration = np.round(rng.normal(md, sd, n))
            energy = np.round(np.clip(rng.normal(me, se, n), 0.0, 1.0), 3)
            for d, e in zip(duration, energy):
                X_part.append([d, e])
                y_part.append(label)
    return (np.array(X_train), np.array(y_train),
            np.array(X_test), np.array(y_test))


