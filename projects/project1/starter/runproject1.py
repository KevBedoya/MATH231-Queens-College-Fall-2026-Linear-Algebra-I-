HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "figures")
os.makedirs(FIG, exist_ok=True)


def fig(name):
    return os.path.join(FIG, name)


# --------------------------------------------------------------------------
# Which part to run
# --------------------------------------------------------------------------

PARTS = {"knn": "1", "kmeans": "2", "descent": "3"}
NAMES = {"1": "k-nearest neighbours", "2": "k-means", "3": "gradient descent"}


def _chosen_parts():
    """The part numbers to run, from the command line or else from TRACK."""
    if len(sys.argv) > 1:
        choice = sys.argv[1].strip().lower()
        if choice == "all":
            return set(PARTS.values())
        if choice in PARTS:
            return {PARTS[choice]}
        sys.exit(f"Unknown part {sys.argv[1]!r}: use knn, kmeans, descent "
                 f"or all.")
    track = str(getattr(p1, "TRACK", "")).strip().lower()
    if track in PARTS:
        return {PARTS[track]}
    if track:
        print(f"TRACK = {track!r} in project1.py is not one of "
              f"\"knn\", \"kmeans\", \"descent\".")
    else:
        print("TRACK is not set in project1.py.")
    print("Running all three parts.  Set TRACK to the part you chose: only "
          "that part is graded.")
    return set(PARTS.values())


CHOSEN = _chosen_parts()
for part in sorted(CHOSEN):
    print(f"Part {part} -- {NAMES[part]}")


def task(label):
    """Decorator: print the label, run the task, report problems, carry on.

    Tasks outside the chosen part are skipped without printing anything.
    """
    def wrap(fn):
        if label.split(".")[0] not in CHOSEN:
            return fn
        print(f"\nOutput of task {label} :")
        try:
            fn()
        except NotImplementedError:
            print("    not implemented yet")
        except Exception:
            last = traceback.format_exc().strip().splitlines()[-1]
            print(f"    ERROR -- {last}")
        return fn
    return wrap


