"""
runproject1.py -- runs the tasks of your part of Project 1, in order.

PROVIDED.  Do not edit this file.  It is what the grader runs.

    python runproject1.py            the part named by TRACK in project1.py
    python runproject1.py kmeans     a different part: knn, kmeans or descent
    python runproject1.py all        all three parts

The grader runs the first form, so the part that is graded is the one TRACK
names.  If TRACK is not set, all three parts run, with a reminder to set it.

It prints one labelled block per task and saves figures into a folder named
figures/ next to this file.  It never opens a window: the live animations are
in play.py.  A task whose function still raises NotImplementedError is reported
as "not implemented yet"; a task whose code crashes is reported with the error,
and the run carries on.
"""

import os
