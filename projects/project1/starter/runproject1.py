@task("3.1")
def _():
    for p in ([0.0, 0.0], [1.0, 2.0], [-1.0, 0.5]):
        print(f"    grad_f({p}) = {p1.grad_f(np.array(p))}")
    rng = np.random.default_rng(0)
    h, worst = 1e-6, 0.0
    for _ in range(50):
        p = rng.uniform(-6, 6, size=2)
        numeric = np.array([(p1.f(p + [h, 0]) - p1.f(p - [h, 0])) / (2 * h),
                            (p1.f(p + [0, h]) - p1.f(p - [0, h])) / (2 * h)])
        worst = max(worst, float(np.max(np.abs(numeric - p1.grad_f(p)))))
    print(f"    largest disagreement with a numerical gradient at 50 random "
          f"points: {worst:.2e}")


@task("3.2")
def _():
    bowl = lambda p: 2 * np.asarray(p, dtype=float)     # grad of x^2 + y^2
    path, ok = p1.gradient_descent(bowl, np.array([1.0, 2.0]), 0.1)
    print(f"    x^2 + y^2 from [1, 2], lr = 0.1: first points "
          f"{[np.round(q, 4).tolist() for q in path[:4]]}")
    print(f"    converged: {ok}, after {len(path) - 1} steps")
    path, ok = p1.gradient_descent(bowl, np.array([1.0, 2.0]), 1.0,
                                   max_iter=20)
    print(f"    same, lr = 1.0, cap 20: converged {ok}, last point "
          f"{np.round(path[-1], 4)}")


@task("3.3")
def _():
    paths = []
    for s in data.marble_starts():
        path, ok = p1.gradient_descent(p1.grad_f, s, 0.3, max_iter=2000)
        paths.append(path)
        e = path[-1]
        print(f"    start {s}: end {np.round(e, 4)}, f = {p1.f(e):.4f}, "
              f"{len(path) - 1} steps, converged {ok}")
    viz.plot_landscape(p1.f, filename=fig("landscape.png"))
    viz.watch_descent(p1.f, paths, title="Five marbles, lr = 0.3",
                      filename=fig("marbles.png"))
    print("    saved figures/landscape.png, marbles.png")


@task("3.4")
def _():
    start = np.array([3.0, 1.5])
    for lr in (0.01, 0.1, 0.5, 1.0, 1.5, 2.0):
        path, ok = p1.gradient_descent(p1.grad_f, start, lr)
        e = path[-1]
        print(f"    start [3, 1.5], lr = {lr:4}: converged {str(ok):5}, "
              f"{len(path) - 1:4d} steps, end {np.round(e, 3)}, "
              f"f = {p1.f(e):.4f}")
    start = np.array([-4.0, 4.6])
    paths = []
    for lr in (0.1, 1.5):
        path, ok = p1.gradient_descent(p1.grad_f, start, lr)
        paths.append(path)
        e = path[-1]
        print(f"    start [-4, 4.6], lr = {lr}: end {np.round(e, 3)}, "
              f"f = {p1.f(e):.4f}")
    viz.watch_descent(p1.f, paths, names=["lr = 0.1", "lr = 1.5"],
                      title="One start, two learning rates",
                      filename=fig("learning_rates.png"))
    print("    saved figures/learning_rates.png")


@task("3.5")
def _():
    starts = data.census_starts()
    ends = [p1.gradient_descent(p1.grad_f, s, 0.5, max_iter=3000)[0][-1]
            for s in starts]
    valleys, counts, which = p1.valley_census(ends)
    order = sorted(range(len(valleys)), key=lambda v: p1.f(valleys[v]))
    print(f"    {len(valleys)} valleys found from {len(starts)} starts:")
    for v in order:
        print(f"      floor at {np.round(valleys[v], 3)}, depth "
              f"f = {p1.f(valleys[v]):7.4f}, reached by {counts[v]:3d} "
              f"starts ({100 * counts[v] / len(starts):4.1f}%)")
    viz.plot_basins(p1.f, starts, which, valleys, filename=fig("basins.png"))
    print("    saved figures/basins.png")

