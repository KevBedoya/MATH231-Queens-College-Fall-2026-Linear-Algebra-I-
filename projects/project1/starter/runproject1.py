np.set_printoptions(precision=4, suppress=True)
HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "figures")
os.makedirs(FIG, exist_ok=True)


def fig(name):
    return os.path.join(FIG, name)


# --------------------------------------------------------------------------
# Which choice to run
# --------------------------------------------------------------------------

CHOICES = {"knn": "1", "kmeans": "2", "descent": "3"}
NAMES = {"1": "k-nearest neighbours", "2": "k-means", "3": "gradient descent"}


def _selected():
    """The choice numbers to run, from the command line or else from TRACK."""
    if len(sys.argv) > 1:
        choice = sys.argv[1].strip().lower()
        if choice == "all":
            return set(CHOICES.values())
        if choice in CHOICES:
            return {CHOICES[choice]}
        sys.exit(f"Unknown choice {sys.argv[1]!r}: use knn, kmeans, descent "
                 f"or all.")
    track = str(getattr(p1, "TRACK", "")).strip().lower()
    if track in CHOICES:
        return {CHOICES[track]}
    if track:
        print(f"TRACK = {track!r} in project1.py is not one of "
              f"\"knn\", \"kmeans\", \"descent\".")
    else:
        print("TRACK is not set in project1.py.")
    print("Running all three choices.  Set TRACK to the choice you made: "
          "only that choice is graded.")
    return set(CHOICES.values())


CHOSEN = _selected()
for choice in sorted(CHOSEN):
    print(f"Choice {choice} -- {NAMES[choice]}")


def step(label):
    """Decorator: print the label, run the step, report problems, carry on.

    Steps of the other choices are skipped without printing anything.
    """
    def wrap(fn):
        if label.split(".")[0] not in CHOSEN:
            return fn
        print(f"\nOutput of step {label} :")
        try:
            fn()
        except NotImplementedError:
            print("    not implemented yet")
        except Exception:
            last = traceback.format_exc().strip().splitlines()[-1]
            print(f"    ERROR -- {last}")
        return fn
    return wrap


